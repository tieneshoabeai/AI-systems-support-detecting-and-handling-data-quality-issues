// Run from frontend with the same NODE_PATH and Chrome used by captures/capture-p0.cjs.
// Reuse that harness's scene/ray helpers so browser checks use the same pick semantics.
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const source = fs.readFileSync('.agents/dataset-3d-core/captures/capture-p0.cjs', 'utf8')
const start = source.indexOf('const HOOK =')
const end = source.indexOf('// Draw calls and triangles per sculptComponent')
assert(start >= 0 && end > start)
const { HOOK, SCENE_HELPERS, FIND_PIXEL } = new Function(source.slice(start, end) + '\nreturn { HOOK, SCENE_HELPERS, FIND_PIXEL }')()
const output = '.agents/dataset-3d-core/crowns'

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader', '--hide-scrollbars', '--force-color-profile=srgb'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' })
    const errors = []
    page.on('pageerror', error => errors.push(String(error)))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.goto('http://localhost:5173/workspaces/3d-dataset', { waitUntil: 'load' })
    await page.waitForSelector('.dataset-3d-canvas canvas')
    await page.waitForTimeout(5000)
    const hook = await page.evaluate(HOOK)
    assert.equal(hook.scenes, 1)
    await page.evaluate(() => { window.__p0modelName = 'Holographic Orbital Data Core v2' })
    await page.evaluate(SCENE_HELPERS)
    const hover = async id => {
      const pixel = await page.evaluate(FIND_PIXEL, id)
      assert(pixel, `visible pixel for ${id}`)
      await page.mouse.move(20, 20)
      await page.mouse.move(pixel.x, pixel.y)
      const label = page.getByRole('tooltip')
      await label.waitFor({ state: 'visible' })
      assert.equal(await label.getAttribute('data-tower-id'), id)
      return { pixel, label: await label.textContent() }
    }
    const attached = await hover('tower-10')
    assert.equal(attached.label, 'Completeness — Đầy đủ')
    await page.screenshot({ path: path.join(output, 'hover-attached.png') })
    await page.keyboard.press('Escape')
    await page.getByRole('tooltip').waitFor({ state: 'hidden' })
    await page.mouse.click(attached.pixel.x, attached.pixel.y)
    assert.equal(await page.locator('#dataset-3d-part-panel').count(), 0)
    const contextPixel = await page.evaluate(FIND_PIXEL, 'tower-01-back-high')
    assert(contextPixel)
    await page.mouse.move(contextPixel.x, contextPixel.y)
    await page.getByRole('tooltip').waitFor({ state: 'hidden' })
    const angle = () => page.evaluate(() => window.__p0helpers.modelRoot().getObjectByName('hero-crown-clock-hand').rotation.y)
    const frozen = await angle()
    await page.waitForTimeout(300)
    assert.equal(await angle(), frozen)
    assert.equal(frozen, 0)
    await page.getByRole('button', { name: 'Tách mô hình' }).click()
    await page.waitForTimeout(900)
    const detached = await hover('tower-10')
    assert.equal(detached.label, attached.label)
    await page.screenshot({ path: path.join(output, 'hover-detached.png') })
    await page.mouse.click(detached.pixel.x, detached.pixel.y)
    assert.equal(await page.locator('#dataset-3d-part-panel').getAttribute('data-part-id'), 'tower-10')
    await page.mouse.move(20, 20)
    await page.getByRole('tooltip').waitFor({ state: 'hidden' })
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.waitForTimeout(800)
    const running = await angle()
    await page.waitForTimeout(500)
    assert.notEqual(await angle(), running)
    assert.equal(errors.length, 0, errors.join('\n'))
    fs.writeFileSync(path.join(output, 'hover-check.json'), JSON.stringify({ attached, detached, attachedClickIgnored: true, detachedClickSelected: true, contextUnlabelled: true, escapeAndLeaveDismiss: true, reducedMotionClockStatic: true, normalClockMoves: true, errors }, null, 2) + '\n')
    console.log('Hover in both poses, click gating, dismissal and reduced-motion clock: PASS')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
